using System.Diagnostics.Metrics;

namespace NoiseCut.Infrastructure.Telemetry;

/// <summary>
/// Every NoiseCut instrument in one place (SPEC §10). Names follow OpenTelemetry conventions; the Prometheus exporter adds
/// <c>_total</c> to counters and the unit suffix (<c>_seconds</c>) to instruments with unit "s".
///
/// Cardinality rule: labels are rule ids, zones, partitions, channels and event types: tens of values, never order or event ids.
/// </summary>
public static class NoiseCutMetrics
{
    public const string MeterName = "NoiseCut";

    private static readonly Meter Meter = new(MeterName);

    // --- engine ---------------------------------------------------------------------------------------------------------
    public static readonly Counter<long> EventsConsumed =
        Meter.CreateCounter<long>("noisecut_events_consumed", description: "Records consumed by the engine, by stage and event type.");

    public static readonly Counter<long> Candidates =
        Meter.CreateCounter<long>("noisecut_candidates", description: "Alert candidates emitted, by rule and status.");

    public static readonly Histogram<double> DetectionLatency =
        Meter.CreateHistogram<double>("noisecut_detection_latency", "s", "detectedAt − triggerProducedAt (wall clock), by rule.");

    public static readonly Gauge<long> ConsumerLag =
        Meter.CreateGauge<long>("noisecut_consumer_lag_records", description: "High watermark − position, per stage and partition.");

    public static readonly Gauge<double> RecordAge =
        Meter.CreateGauge<double>("noisecut_record_age", "s", "Wall-clock age of the last record processed, per stage and partition.");

    public static readonly Gauge<long> EngineZoneHourOrders =
        Meter.CreateGauge<long>("noisecut_engine_zone_hour_orders", description: "Rule B counts this engine instance holds for the current hour, by zone and kind.");

    public static readonly Counter<long> DeadLettered =
        Meter.CreateCounter<long>("noisecut_dead_lettered", description: "Records sent to order-events-dlq.");

    // --- notifier -------------------------------------------------------------------------------------------------------
    public static readonly Counter<long> IntakeCandidates =
        Meter.CreateCounter<long>("noisecut_intake_candidates", description: "Candidates received by the notifier; repeat=true means the (alertKey, status) was seen before.");

    public static readonly Counter<long> Suppressed =
        Meter.CreateCounter<long>("noisecut_suppressed", description: "Candidates that did not become notifications, by rule and reason.");

    public static readonly Counter<long> Notifications =
        Meter.CreateCounter<long>("noisecut_notifications", description: "Notifications delivered, by channel and kind.");

    public static readonly Histogram<double> DeliveryLatency =
        Meter.CreateHistogram<double>("noisecut_delivery_latency", "s", "Delivered-at − triggerProducedAt, by channel. Includes any intentional groupWait.");

    public static readonly Counter<long> DeliveryFailures =
        Meter.CreateCounter<long>("noisecut_delivery_failures", description: "Failed delivery attempts (each retry counts), by channel.");

    public static readonly Counter<long> DeliveriesDead =
        Meter.CreateCounter<long>("noisecut_deliveries_dead", description: "Deliveries that gave up after the maximum attempts, by channel.");

    // --- api / sink -----------------------------------------------------------------------------------------------------
    public static readonly Counter<long> SinkReceipts =
        Meter.CreateCounter<long>("noisecut_sink_receipts", description: "Webhook requests accepted by the built-in sink.");

    public static readonly Counter<long> SinkDuplicateReceipts =
        Meter.CreateCounter<long>("noisecut_sink_duplicate_receipts", description: "Webhook requests whose Idempotency-Key had already been received.");

    // --- simulator ------------------------------------------------------------------------------------------------------
    public static readonly Counter<long> SimEvents =
        Meter.CreateCounter<long>("noisecut_sim_events", description: "Events generated by the simulator (ground truth), by type and zone.");

    public static readonly Gauge<long> SimZoneHourOrders =
        Meter.CreateGauge<long>("noisecut_sim_zone_hour_orders", description: "Ground-truth placed/cancelled counts for the current sim hour, by zone.");

    public static readonly Gauge<long> SimActiveScenarios =
        Meter.CreateGauge<long>("noisecut_sim_active_scenarios", description: "Scenarios currently active in sim time, by name.");

    public static readonly Gauge<double> SimOrdersPerMinute =
        Meter.CreateGauge<double>("noisecut_sim_orders_per_minute", description: "Configured peak orders per sim minute.");

    public static readonly Counter<long> SimChaos =
        Meter.CreateCounter<long>("noisecut_sim_chaos", description: "Chaos actions applied by the simulator, by kind (held, duplicated, burst).");
}
